const { chromium } = require('../runtime/browser/node_modules/playwright');
const fs = require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const external=[];page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:8088/')&&!r.url().startsWith('data:'))external.push(r.url());});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8088/');
 await page.locator('#username').fill(process.env.UII_TEST_USER||'Test_Admin');
 await page.locator('#password').fill(process.env.UII_TEST_PASSWORD);
 await page.waitForTimeout(2100);
 await page.locator('input[name=login]').click();
 await page.goto('http://127.0.0.1:8088/');
 await page.waitForLoadState('networkidle');
 await page.screenshot({path:'runtime/portal-desktop.png',fullPage:true});
 await page.locator('#uii-theme').click();
 if(await page.locator('html').getAttribute('data-theme')!=='dark')throw Error('Dark theme');
 await page.reload();
 if(await page.locator('html').getAttribute('data-theme')!=='dark')throw Error('Theme persistence');
 await page.screenshot({path:'runtime/portal-dark.png',fullPage:true});
 console.log('PASS dark theme and persistence');
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://127.0.0.1:8088/app.php/uii/new?kind=complaint');
 await page.waitForLoadState('networkidle');
 await page.locator('#uii-menu').click();
 if(await page.locator('#uii-menu').getAttribute('aria-expanded')!=='true')throw Error('Mobile menu');
 const size=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:innerWidth}));
 if(size.scroll>size.width)throw Error('Mobile overflow '+JSON.stringify(size));
 await page.screenshot({path:'runtime/portal-mobile.png',fullPage:true});
 console.log('PASS mobile 390px without horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 if(external.length)throw Error('External resources: '+external.join(', '));
 console.log('PASS browser JavaScript without errors and no external resources');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
