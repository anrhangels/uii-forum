const {chromium}=require('../runtime/browser/node_modules/playwright');
(async()=>{
 const browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8088/ucp.php?mode=login');
 await page.locator('#username').fill(process.env.UII_TEST_USER||'Test_Admin');await page.locator('#password').fill(process.env.UII_TEST_PASSWORD);await page.waitForTimeout(2100);await page.locator('input[name=login]').click();
 await page.goto('http://127.0.0.1:8088/app.php/uii/admin');
 if(await page.locator('.admin-launchpad>a').count()<3)throw Error('Admin tiles');
 await page.screenshot({path:'runtime/admin-refreshed.png',fullPage:true});
 await page.goto('http://127.0.0.1:8088/app.php/uii/employees');
 await page.locator('#employee-search').fill('no-such-employee');await page.getByRole('button',{name:'Найти',exact:true}).click();
 if(await page.locator('.employee-row:visible').count()!==0)throw Error('Employee search hides rows');
 if(!await page.locator('#employee-no-results').isVisible())throw Error('Search empty state');
 await page.goto('http://127.0.0.1:8088/app.php/uii/employees');
 await page.locator('[data-open-create]').click();
 if(await page.locator('#manage').getAttribute('open')===null)throw Error('Create form');
 await page.screenshot({path:'runtime/employees-refreshed.png',fullPage:true});
 const action=page.locator('.employee-actions').first();await action.locator('summary').click();
 if(!await action.locator('select[name=role]').isVisible())throw Error('Employee inline actions');
 await page.setViewportSize({width:390,height:844});
 const widths=await page.evaluate(()=>[document.documentElement.scrollWidth,innerWidth]);
 if(widths[0]>widths[1])throw Error('Employees mobile overflow '+widths);
 await page.goto('http://127.0.0.1:8088/app.php/uii/admin');
 const adminWidths=await page.evaluate(()=>[document.documentElement.scrollWidth,innerWidth]);if(adminWidths[0]>adminWidths[1])throw Error('Admin mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS management hub, employee search, creation panel, inline actions and mobile layouts');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
